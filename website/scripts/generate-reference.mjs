#!/usr/bin/env node
// Generates the Reference section (components, functions, properties) from a
// local Apache JMeter installation:
//   printable_docs/usermanual/component_reference.html
//   printable_docs/usermanual/functions.html
//   printable_docs/usermanual/properties_reference.html
//   bin/jmeter.properties
//
// Usage:  JMETER_HOME=/path/to/apache-jmeter-5.6.3 npm run generate:reference
// Without JMETER_HOME it looks for ../apache-jmeter-* next to the website folder.
// The output in docs/reference is committed, so CI does not need JMeter.

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as cheerio from 'cheerio';
import TurndownService from 'turndown';
import {gfm} from 'turndown-plugin-gfm';

const here = path.dirname(fileURLToPath(import.meta.url));
const siteDir = path.resolve(here, '..');
const repoDir = path.resolve(siteDir, '..');
const refDir = path.join(siteDir, 'docs', 'reference');
const imgOutDir = path.join(siteDir, 'static', 'img', 'jmeter');
const IMG_URL = '/img/jmeter';

// ---------------------------------------------------------------- locate JMeter

function findJmeterHome() {
  if (process.env.JMETER_HOME) return path.resolve(process.env.JMETER_HOME);
  const candidates = fs
    .readdirSync(repoDir)
    .filter((d) => /^apache-jmeter-\d/.test(d))
    .sort()
    .reverse();
  return candidates.length ? path.join(repoDir, candidates[0]) : null;
}

const jmeterHome = findJmeterHome();
const manualDir = jmeterHome && path.join(jmeterHome, 'printable_docs', 'usermanual');
if (!manualDir || !fs.existsSync(path.join(manualDir, 'component_reference.html'))) {
  console.error(
    '[reference] JMeter installation not found. Set JMETER_HOME to your apache-jmeter-x.y.z folder.',
  );
  process.exit(1);
}
const jmeterVersion =
  process.env.JMETER_VERSION || (path.basename(jmeterHome).match(/(\d+\.\d+(?:\.\d+)?)/) || [])[1] || 'unknown';
console.log(`[reference] Using JMeter ${jmeterVersion} at ${jmeterHome}`);

const readManual = (name) =>
  fs
    .readFileSync(path.join(manualDir, name), 'utf8')
    // <a name="x"/> is not self-closing in HTML; make it a real empty anchor.
    .replace(/<a name="([^"]+)"\s*\/>/g, '<a name="$1"></a>');

// ------------------------------------------------------------------ helpers

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const stripNumber = (s) => s.replace(/^\s*[\d.]+[a-z]?\.?\s+/, '').replace(/\s+/g, ' ').trim();

const yaml = (obj) =>
  '---\n' +
  Object.entries(obj)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === 'string' ? JSON.stringify(v) : v}`)
    .join('\n') +
  '\n---\n\n';

const banner = (src) =>
  `<!-- Generated by website/scripts/generate-reference.mjs from JMeter ${jmeterVersion} (${src}). Do not edit by hand. -->\n\n`;

const sourceNote = (page) =>
  `:::info[Source]\n\nAdapted from the [Apache JMeter ${jmeterVersion} user manual](https://jmeter.apache.org/usermanual/${page}) (Apache License 2.0).\n\n:::\n\n`;

function firstSentence(md) {
  const text = md
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/:::[\s\S]*?:::/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[`*_\\]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  const m = text.match(/^(.{20,200}?[.!?])(\s|$)/);
  return (m ? m[1] : text.slice(0, 160)).trim();
}

// ---------------------------------------------------------- anchor registry
// anchor id -> output file (relative to refDir), so manual links can be rewritten.

const anchors = {component_reference: new Map(), functions: new Map(), properties_reference: new Map()};
const pageIndex = {
  component_reference: 'components/index.md',
  functions: 'functions.md',
  properties_reference: 'properties.md',
};

function registerInlineAnchors(manual, html, file) {
  for (const m of html.matchAll(/<a name="([^"]+)"/g)) {
    if (!anchors[manual].has(m[1])) anchors[manual].set(m[1], file);
  }
}

function rel(fromFile, toFile) {
  let r = path.posix.relative(path.posix.dirname(fromFile), toFile);
  if (!r.startsWith('.')) r = './' + r;
  return r;
}

function rewriteHref(href, manual, fromFile) {
  if (!href) return href;
  href = href.trim();
  if (/^(https?:|mailto:)/i.test(href)) return href;
  if (href.startsWith('#')) {
    const id = href.slice(1);
    const target = anchors[manual].get(id) || fromFile;
    return target === fromFile ? href : `${rel(fromFile, target)}#${id}`;
  }
  let h = href.replace(/^(\.\.\/usermanual\/)+/, '').replace(/^\.\//, '');
  const m = h.match(/^(component_reference|functions|properties_reference)\.html(?:#(.*))?$/);
  if (m) {
    const [, page, id] = m;
    if (!id) return rel(fromFile, pageIndex[page]);
    const target = anchors[page].get(id);
    // Some manual links point at components that no longer exist; link the page instead.
    return target ? `${rel(fromFile, target)}#${id}` : rel(fromFile, pageIndex[page]);
  }
  if (h.startsWith('../../docs/api/')) return 'https://jmeter.apache.org/api/' + h.slice('../../docs/api/'.length);
  if (h.startsWith('../demos/')) return 'https://jmeter.apache.org/demos/' + h.slice('../demos/'.length);
  if (h.startsWith('../')) return 'https://jmeter.apache.org/' + h.replace(/^(\.\.\/)+/, '');
  return 'https://jmeter.apache.org/usermanual/' + h;
}

const copiedImages = new Set();
function rewriteImg(src) {
  if (!src || /void\.gif$/.test(src)) return null;
  if (/^https?:/.test(src)) return src;
  const m = src.match(/(?:\.\.\/)*docs\/images\/(.+)$/);
  if (!m) return null;
  const relPath = m[1];
  const from = path.join(jmeterHome, 'docs', 'images', relPath);
  if (!fs.existsSync(from)) return null;
  const to = path.join(imgOutDir, relPath);
  if (!copiedImages.has(relPath)) {
    fs.mkdirSync(path.dirname(to), {recursive: true});
    fs.copyFileSync(from, to);
    copiedImages.add(relPath);
  }
  return `${IMG_URL}/${relPath}`;
}

// ------------------------------------------------------- HTML clean-up pass

function cleanHtml(html) {
  const $ = cheerio.load(`<div id="root">${html}</div>`, null, false);
  const root = $('#root');

  // Code boxes are drawn as 3x3 tables with dark border cells around a <pre>.
  root.find('table').each((_, t) => {
    const $t = $(t);
    if ($t.find('> tbody > tr > td[bgcolor="#023264"], > tr > td[bgcolor="#023264"]').length) {
      const pre = $t.find('pre').first();
      const text = pre.length ? pre.text() : $t.find('td[bgcolor="#ffffff"]').text();
      $t.replaceWith($('<pre></pre>').text(text.replace(/^\n+|\s+$/g, '')));
    }
  });
  // Yellow boxes are notes.
  root.find('table[bgcolor="#bbbb00"]').each((_, t) => {
    const $t = $(t);
    const inner = $t.find('td').first().html() || '';
    $t.replaceWith(`<div class="jm-note">${inner}</div>`);
  });
  // Unwrap purely presentational wrappers.
  root.find('font, center, blockquote, span, div.description, div[align]').each((_, el) => {
    $(el).replaceWith($(el).contents());
  });
  root.find('hr, script, style').remove();
  // Empty tables left over from the page layout.
  root.find('table').each((_, t) => {
    if (!$(t).text().trim() && !$(t).find('img').length) $(t).remove();
  });
  return {$, root};
}

// ----------------------------------------------------------- markdown pass

function makeTurndown(manual, fromFile, {inline = false} = {}) {
  const td = new TurndownService({
    headingStyle: 'atx',
    codeBlockStyle: 'fenced',
    bulletListMarker: '-',
    emDelimiter: '_',
    hr: '---',
  });
  td.use(gfm);
  const baseEscape = td.escape.bind(td);
  // .md pages render raw HTML, so escape angle brackets in plain text.
  td.escape = (s) => baseEscape(s).replace(/</g, '&lt;').replace(/>/g, '&gt;');

  const codeSpan = (text) => {
    const t = text.replace(/\s+/g, ' ').trim();
    if (!t) return '';
    const fence = t.includes('`') ? '`` ' : '`';
    const close = t.includes('`') ? ' ``' : '`';
    return fence + t + close;
  };

  td.addRule('tt', {
    filter: ['tt', 'code'],
    replacement: (content, node) => {
      if (node.parentNode && node.parentNode.nodeName === 'PRE') return content;
      const a = node.querySelector && node.querySelector('a[href]');
      const code = codeSpan(node.textContent);
      if (a) return `[${code}](${rewriteHref(a.getAttribute('href'), manual, fromFile)})`;
      return code;
    },
  });

  td.addRule('pre', {
    filter: 'pre',
    replacement: (_content, node) => {
      const text = node.textContent.replace(/^\n+|\s+$/g, '');
      if (!text) return '';
      if (inline) return text.split('\n').map(codeSpan).filter(Boolean).join('<br/>');
      const lang = /^\s*[\w.-]+\s*=/.test(text) && !/[;{}]/.test(text) ? 'properties' : '';
      const fence = text.includes('```') ? '~~~~' : '```';
      return `\n\n${fence}${lang}\n${text}\n${fence}\n\n`;
    },
  });

  td.addRule('note', {
    filter: (node) => node.nodeName === 'DIV' && node.classList.contains('jm-note'),
    replacement: (content) => {
      const body = content.trim();
      if (!body) return '';
      if (inline) return `**Note:** ${body}`;
      return `\n\n:::note\n\n${body}\n\n:::\n\n`;
    },
  });

  td.addRule('anchor-target', {
    filter: (node) => node.nodeName === 'A' && node.getAttribute('name') && !node.getAttribute('href'),
    replacement: (content, node) => `<a id="${node.getAttribute('name')}"></a>${content}`,
  });

  td.addRule('link', {
    filter: (node) => node.nodeName === 'A' && node.getAttribute('href'),
    replacement: (content, node) => {
      const href = rewriteHref(node.getAttribute('href'), manual, fromFile);
      const text = content.trim() || href;
      return `[${text}](${href})`;
    },
  });

  td.addRule('img', {
    filter: 'img',
    replacement: (_c, node) => {
      const src = rewriteImg(node.getAttribute('src'));
      if (!src) return '';
      const alt = (node.getAttribute('alt') || node.getAttribute('title') || 'Screenshot').replace(/[\[\]]/g, '');
      return inline ? `![${alt}](${src})` : `\n\n![${alt}](${src})\n\n`;
    },
  });

  td.addRule('dl', {
    filter: 'dl',
    replacement: (_c, node) => {
      const items = [];
      let current = null;
      for (const child of node.childNodes) {
        if (child.nodeName === 'DT') {
          current = {dt: makeTurndown(manual, fromFile, {inline: true}).turndown(child.innerHTML).trim(), dd: ''};
          items.push(current);
        } else if (child.nodeName === 'DD') {
          const dd = makeTurndown(manual, fromFile, {inline}).turndown(child.innerHTML).trim();
          if (current) current.dd += (current.dd ? '\n\n' : '') + dd;
          else items.push({dt: '', dd});
        }
      }
      const md = items
        .map(({dt, dd}) => {
          const head = dt ? `**${dt.replace(/^\*\*|\*\*$/g, '')}**` : '';
          const body = dd ? (inline ? dd.replace(/\n+/g, ' ') : indent(dd, 2)) : '';
          return inline ? `${head}: ${body}` : `- ${head}${body ? (head ? '\n\n' + body : body.trimStart()) : ''}`;
        })
        .join(inline ? '<br/>' : '\n\n');
      return inline ? md : `\n\n${md}\n\n`;
    },
  });

  td.addRule('table', {
    filter: 'table',
    replacement: (_c, node) => tableToMarkdown(node, manual, fromFile, inline),
  });

  // Headings inside a section sit below the section's own heading level.
  td.addRule('subheadings', {
    filter: ['h2', 'h3', 'h4', 'h5'],
    replacement: (content, node) => {
      const text = content.replace(/\s+/g, ' ').trim();
      if (!text) return '';
      if (inline) return `**${text}**`;
      const level = {H2: 4, H3: 4, H4: 4, H5: 5}[node.nodeName];
      return `\n\n${'#'.repeat(level)} ${text}\n\n`;
    },
  });

  return td;
}

const indent = (s, n) =>
  s
    .split('\n')
    .map((l) => (l.trim() ? ' '.repeat(n) + l : ''))
    .join('\n');

function cellText(cell, manual, fromFile) {
  return makeTurndown(manual, fromFile, {inline: true})
    .turndown(cell.innerHTML || '')
    .trim()
    .replace(/ {2,}\n/g, '\n')
    .replace(/\n{2,}/g, '<br/><br/>')
    .replace(/\n/g, ' ')
    .replace(/\|/g, '\\|');
}

function rowsOf(table) {
  const rows = [];
  const walk = (n) => {
    for (const c of n.childNodes) {
      if (c.nodeName === 'TR') rows.push(c);
      else if (['TBODY', 'THEAD', 'TFOOT'].includes(c.nodeName)) walk(c);
    }
  };
  walk(table);
  return rows.map((tr) => [...tr.childNodes].filter((c) => c.nodeName === 'TD' || c.nodeName === 'TH'));
}

// Parameter tables (Attribute / Description / Required) become a definition list,
// Playwright-docs style, which reads better than a 3-column table on small screens.
function isParamTable(rows) {
  const head = rows[0] && rows[0].map((c) => c.textContent.trim().toLowerCase());
  return head && head[0] === 'attribute' && head[1] === 'description';
}

function tableToMarkdown(node, manual, fromFile, inline) {
  const rows = rowsOf(node).filter((r) => r.length);
  if (!rows.length) return '';
  if (isParamTable(rows) && !inline) {
    const items = rows.slice(1).map((cells) => {
      const name = cells[0] ? cells[0].textContent.replace(/\s+/g, ' ').trim() : '';
      const desc = cells[1] ? makeTurndown(manual, fromFile).turndown(cells[1].innerHTML).trim() : '';
      const req = cells[2] ? cells[2].textContent.replace(/\s+/g, ' ').trim() : '';
      const reqHtml = req ? ` <span class="jm-required" data-required="${/^yes/i.test(req) ? 'yes' : 'no'}">Required: ${req.replace(/</g, '&lt;')}</span>` : '';
      return `- **${name.replace(/\*/g, '\\*')}**${reqHtml}${desc ? '\n\n' + indent(desc, 2) : ''}`;
    });
    return `\n\n<div class="jm-params">\n\n${items.join('\n\n')}\n\n</div>\n\n`;
  }
  const width = Math.max(...rows.map((r) => r.length));
  const md = rows.map((r) => {
    const cells = r.map((c) => cellText(c, manual, fromFile) || ' ');
    while (cells.length < width) cells.push(' ');
    return `| ${cells.join(' | ')} |`;
  });
  if (inline) return rows.map((r) => r.map((c) => cellText(c, manual, fromFile)).join(' · ')).join('<br/>');
  if (width === 1) return '\n\n' + rows.map((r) => cellText(r[0], manual, fromFile)).join('\n\n') + '\n\n';
  const sep = `| ${Array(width).fill('---').join(' | ')} |`;
  return `\n\n${[md[0], sep, ...md.slice(1)].join('\n')}\n\n`;
}

function htmlToMarkdown(html, manual, fromFile, {promoteLabels = 0} = {}) {
  const {$, root} = cleanHtml(html);
  // Turn "<p><b>Parameters</b></p>" style labels into headings.
  if (promoteLabels) {
    root.find('p').each((_, p) => {
      const $p = $(p);
      const kids = $p.children();
      if (kids.length === 1 && kids.is('b') && $p.text().trim() === kids.text().trim()) {
        const label = kids.text().trim().replace(/:$/, '');
        if (/^(Parameters|See Also|Control Panel)$/i.test(label)) {
          const nice = label === 'See Also' ? 'See also' : label === 'Control Panel' ? 'Control panel' : label;
          $p.replaceWith(`<p>@@H${promoteLabels}@@${nice}</p>`);
        }
      }
    });
  }
  let md = makeTurndown(manual, fromFile).turndown(root.html() || '');
  md = md.replace(/^@@H(\d)@@(.*)$/gm, (_m, n, t) => `${'#'.repeat(Number(n))} ${t}`);
  return tidy(md);
}

function tidy(md) {
  return md
    .replace(/[ \t]+$/gm, (m) => (m.length >= 2 ? '' : ''))
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^\s+|\s+$/g, '')
    .concat('\n');
}

// ------------------------------------------------------------ chunking

// Splits a manual page into ordered markers: sections (<a name><strong>) and items (<h3><a name>).
function scan(html) {
  const markers = [];
  const sectionRe = /<a name="([^"]+)"><strong>([^<]+)<\/strong><\/a>/g;
  const itemRe = /<h3>\s*<a name="([^"]+)">([^<]+)<\/a>\s*<\/h3>/g;
  for (const m of html.matchAll(sectionRe)) markers.push({type: 'section', id: m[1], title: m[2], start: m.index, end: m.index + m[0].length});
  for (const m of html.matchAll(itemRe)) markers.push({type: 'item', id: m[1], title: m[2], start: m.index, end: m.index + m[0].length});
  markers.sort((a, b) => a.start - b.start);
  const bodyEnd = html.lastIndexOf('</body>') > 0 ? html.lastIndexOf('</body>') : html.length;
  markers.forEach((m, i) => {
    m.html = html.slice(m.end, i + 1 < markers.length ? markers[i + 1].start : bodyEnd);
    m.title = stripNumber(cheerio.load(m.title).text());
  });
  return markers;
}

// Remove the footer navigation that ends every manual page.
const stripFooter = (html) => {
  const i = html.lastIndexOf('<td bgcolor="#525D76">\n<div align="right"><a href="index.html">');
  const t = i > 0 ? html.lastIndexOf('<table', i) : -1;
  return t > 0 ? html.slice(0, t) : html;
};

const write = (file, content) => {
  const full = path.join(refDir, file);
  fs.mkdirSync(path.dirname(full), {recursive: true});
  fs.writeFileSync(full, content);
};

// =========================================================== components

const componentCategories = {
  samplers: {slug: 'samplers', label: 'Samplers', emoji: '🎯'},
  logic_controllers: {slug: 'logic-controllers', label: 'Logic Controllers', emoji: '🔀'},
  listeners: {slug: 'listeners', label: 'Listeners', emoji: '📊'},
  config_elements: {slug: 'config-elements', label: 'Configuration Elements', emoji: '⚙️'},
  assertions: {slug: 'assertions', label: 'Assertions', emoji: '✅'},
  timers: {slug: 'timers', label: 'Timers', emoji: '⏱️'},
  preprocessors: {slug: 'pre-processors', label: 'Pre-Processors', emoji: '⏮️'},
  postprocessors: {slug: 'post-processors', label: 'Post-Processors', emoji: '⏭️'},
  Miscellaneous_Features: {slug: 'test-plan-and-thread-groups', label: 'Test Plan, Thread Groups & More', emoji: '🧵'},
};

function buildComponents() {
  const html = stripFooter(readManual('component_reference.html'));
  const markers = scan(html);
  // Group markers into categories.
  const groups = [];
  let intro = null;
  let current = null;
  for (const m of markers) {
    if (m.type === 'section') {
      if (m.id === 'introduction') {
        intro = m;
        current = null;
        continue;
      }
      const cat = componentCategories[m.id] || {slug: slugify(m.title), label: m.title, emoji: '📦'};
      current = {...cat, id: m.id, intro: m, items: []};
      groups.push(current);
    } else if (current) {
      current.items.push(m);
    }
  }
  // Pass 1: register anchors.
  for (const g of groups) {
    const file = `components/${g.slug}.md`;
    anchors.component_reference.set(g.id, file);
    registerInlineAnchors('component_reference', g.intro.html, file);
    for (const it of g.items) {
      anchors.component_reference.set(it.id, file);
      registerInlineAnchors('component_reference', it.html, file);
    }
  }
  if (intro) anchors.component_reference.set('introduction', 'components/index.md');

  // Pass 2: render.
  return () => {
    groups.forEach((g, i) => {
      const file = `components/${g.slug}.md`;
      const introMd = htmlToMarkdown(g.intro.html, 'component_reference', file);
      let body = '';
      for (const it of g.items) {
        const md = htmlToMarkdown(it.html, 'component_reference', file, {promoteLabels: 3});
        body += `## ${it.title} {#${it.id}}\n\n${md}\n`;
      }
      const description = firstSentence(introMd) || `${g.label} in Apache JMeter.`;
      write(
        file,
        yaml({
          title: g.label,
          sidebar_label: g.label,
          sidebar_position: i + 1,
          description,
          toc_max_heading_level: 2,
        }) +
          banner('component_reference.html') +
          sourceNote(`component_reference.html#${g.id}`) +
          `<a id="${g.id}"></a>\n\n` +
          introMd +
          '\n' +
          body,
      );
      console.log(`[reference] components/${g.slug}.md (${g.items.length} components)`);
    });

    // Index page with every component.
    const introMd = intro ? htmlToMarkdown(intro.html, 'component_reference', 'components/index.md') : '';
    let list = '';
    for (const g of groups) {
      list += `## ${g.emoji} ${g.label}\n\n`;
      list += g.items.map((it) => `- [${it.title}](./${g.slug}.md#${it.id})`).join('\n') + '\n\n';
    }
    write(
      'components/index.md',
      yaml({
        title: 'Component Reference',
        sidebar_label: 'Overview',
        sidebar_position: 0,
        slug: '/reference/components',
        description: `Every built-in Apache JMeter ${jmeterVersion} test element: samplers, controllers, listeners, config elements, assertions, timers and processors.`,
      }) +
        banner('component_reference.html') +
        sourceNote('component_reference.html') +
        `<a id="introduction"></a>\n\n` +
        introMd +
        '\n' +
        list,
    );
    write(
      'components/_category_.json',
      JSON.stringify({label: '🧩 Components', position: 2, collapsed: true, link: {type: 'doc', id: 'reference/components/index'}}, null, 2) + '\n',
    );
    return groups;
  };
}

// ============================================================ functions

function buildFunctions() {
  const html = stripFooter(readManual('functions.html'));
  const markers = scan(html);
  const file = 'functions.md';
  for (const m of markers) {
    anchors.functions.set(m.id, file);
    registerInlineAnchors('functions', m.html, file);
  }
  return () => {
    let out = '';
    let functionNames = [];
    const seen = new Set();
    markers.forEach((m, i) => {
      if (i === 0 && m.type === 'section') {
        // "Functions and Variables" page intro.
        out += htmlToMarkdown(m.html, 'functions', file) + '\n';
        return;
      }
      let id = m.id;
      if (seen.has(id)) id = `${id}-list`;
      seen.add(id);
      const md = htmlToMarkdown(m.html, 'functions', file, {promoteLabels: m.type === 'item' ? 4 : 0});
      if (m.type === 'section') out += `## ${m.title} {#${id}}\n\n${md}\n`;
      else {
        functionNames.push(m.title);
        out += `### ${m.title} {#${id}}\n\n${md}\n`;
      }
    });
    write(
      file,
      yaml({
        title: 'Functions and Variables',
        sidebar_label: '🧮 Functions',
        sidebar_position: 3,
        description: `All ${functionNames.length} built-in JMeter ${jmeterVersion} functions such as __Random, __time and __P, plus pre-defined variables and properties.`,
        toc_max_heading_level: 3,
      }) +
        banner('functions.html') +
        sourceNote('functions.html') +
        out,
    );
    console.log(`[reference] functions.md (${functionNames.length} functions)`);
  };
}

// =========================================================== properties

function buildProperties() {
  const html = stripFooter(readManual('properties_reference.html'));
  const markers = scan(html).filter((m) => m.type === 'section');
  const file = 'properties.md';
  for (const m of markers) {
    anchors.properties_reference.set(m.id, file);
    registerInlineAnchors('properties_reference', m.html, file);
  }
  return () => {
    let out = '';
    let count = 0;
    const usedIds = new Set();
    for (const m of markers) {
      if (m.id === 'introduction') {
        out += htmlToMarkdown(m.html, 'properties_reference', file) + '\n';
        continue;
      }
      // Each property row becomes its own heading so it shows up in search.
      const {$, root} = cleanHtml(m.html);
      const blocks = [];
      root.children().each((_, el) => blocks.push(el));
      let md = '';
      let pending = '';
      const flush = () => {
        if (pending.trim()) md += makeTurndown('properties_reference', file).turndown(pending) + '\n\n';
        pending = '';
      };
      const nodes = root.contents().toArray();
      for (const n of nodes) {
        const isParams =
          n.type === 'tag' && n.name === 'table' && $(n).find('th').first().text().trim().toLowerCase() === 'attribute';
        if (!isParams) {
          pending += $.html(n);
          continue;
        }
        // Drop the "Parameters" label right before the table.
        pending = pending.replace(/<p>\s*<b>Parameters<\/b>\s*<\/p>\s*$/, '');
        flush();
        $(n)
          .find('tr')
          .each((_, tr) => {
            const cells = $(tr).children('td');
            if (cells.length < 2) return;
            const name = $(cells[0]).text().replace(/\s+/g, ' ').trim();
            let id = name.replace(/[^\w.-]+/g, '_');
            while (usedIds.has(id)) id += '_';
            usedIds.add(id);
            const desc = makeTurndown('properties_reference', file).turndown($(cells[1]).html() || '').trim();
            const req = cells[2] ? $(cells[2]).text().trim() : '';
            md += `### \`${name}\` {#${id}}\n\n${desc}\n\n${/^yes/i.test(req) ? '**Required:** Yes\n\n' : ''}`;
            count++;
          });
      }
      flush();
      out += `## ${m.title} {#${m.id}}\n\n${tidy(md)}\n`;
    }
    write(
      file,
      yaml({
        title: 'Properties Reference',
        sidebar_label: '🔧 Properties',
        sidebar_position: 4,
        description: `All ${count} JMeter ${jmeterVersion} properties you can set in user.properties or with -J on the command line.`,
        toc_max_heading_level: 2,
      }) +
        banner('properties_reference.html') +
        sourceNote('properties_reference.html') +
        ':::tip\n\nDo not edit `jmeter.properties`. Put your overrides in `bin/user.properties`, or pass them with `-Jname=value` on the command line. See [TOD#003](../tips.md#tod003).\n\n:::\n\n' +
        out,
    );
    console.log(`[reference] properties.md (${count} properties)`);
  };
}

// ================================================== jmeter.properties file

function buildPropertiesFile() {
  const src = path.join(jmeterHome, 'bin', 'jmeter.properties');
  if (!fs.existsSync(src)) return;
  const text = fs.readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
  const lines = text.split('\n');
  // Sections look like:  #----\n# Title\n#----
  const sections = [];
  let cur = {title: 'General', lines: []};
  for (let i = 0; i < lines.length; i++) {
    if (/^#-{10,}\s*$/.test(lines[i]) && /^#\s*\S/.test(lines[i + 1] || '') && /^#-{10,}\s*$/.test(lines[i + 2] || '')) {
      sections.push(cur);
      cur = {title: lines[i + 1].replace(/^#\s*/, '').trim(), lines: []};
      i += 2;
      continue;
    }
    cur.lines.push(lines[i]);
  }
  sections.push(cur);
  let md = '';
  let keys = 0;
  const used = new Set();
  for (const s of sections) {
    const body = s.lines.join('\n').replace(/^\n+|\s+$/g, '');
    if (!body) continue;
    // Skip the licence header.
    const cleaned = s.title === 'General' ? body.replace(/^#\n# Licensed[\s\S]*?limitations under the License\.\n#\n*/, '') : body;
    if (!cleaned.trim()) continue;
    let id = 'section-' + slugify(s.title);
    while (used.has(id)) id += '-x';
    used.add(id);
    keys += (cleaned.match(/^#?[a-zA-Z][\w.-]*=/gm) || []).length;
    md += `## ${s.title.replace(/[<>]/g, '')} {#${id}}\n\n\`\`\`properties\n${cleaned}\n\`\`\`\n\n`;
  }
  write(
    'jmeter-properties-file.md',
    yaml({
      title: 'Default jmeter.properties',
      sidebar_label: '📄 jmeter.properties',
      sidebar_position: 5,
      description: `The complete default bin/jmeter.properties from JMeter ${jmeterVersion}, split by section.`,
      toc_max_heading_level: 2,
    }) +
      banner('bin/jmeter.properties') +
      `This is the default \`bin/jmeter.properties\` shipped with JMeter ${jmeterVersion} (about ${keys} settings), split into its sections so you can search it. ` +
      'Lines starting with `#` are commented out and show the default value. For what each property does, see the [Properties Reference](./properties.md).\n\n' +
      ':::warning\n\nCopy a property into `bin/user.properties` to change it. Editing `jmeter.properties` itself means your changes are lost when you upgrade JMeter.\n\n:::\n\n' +
      md,
  );
  console.log(`[reference] jmeter-properties-file.md (${sections.length} sections)`);
}

